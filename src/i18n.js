/* Customer-facing bot texts in two languages (mirrors @LiveiraStore_bot src/i18n.ts).
 *  - Locales: "pt" (pt-BR) and "en". Admin panel, admin commands, admin DMs and the group feed are NOT translated.
 *  - t(lang, key, vars): "{name}" placeholders are replaced verbatim — callers escape HTML (tgEsc) before passing.
 *  - Every key must exist in both dictionaries (tests/bot checks parity).
 *  - users.lang / users.lang_chosen (migration 0012). Without the migration every user is treated as English + picked. */

export const LOCALES = ["pt", "en"];
export const DEFAULT_LANG = "pt"; // new users before picking (DB default)

export function normalizeLang(v) {
  const s = String(v || "").trim().toLowerCase();
  return s === "en" || s.startsWith("en") ? "en" : s === "pt" || s.startsWith("pt") ? "pt" : null;
}

/** Language for a user row / object ({ lang }), English when unknown (pre-migration rows behaved as English). */
export function langOf(u) {
  return normalizeLang(u?.lang) || "en";
}

/** Language of a Telegram user id for background messages (payment notices, cron). Never throws. */
export async function getUserLang(env, userId) {
  try {
    const r = await env.DB.prepare("SELECT lang FROM users WHERE user_id=?").bind(Number(userId)).first();
    return langOf(r);
  } catch {
    return "en"; // column missing (migration 0012 not applied)
  }
}

/** Set the language and mark it as chosen. Returns false when the columns are missing. */
export async function setUserLang(env, userId, lang) {
  try {
    await env.DB.prepare("UPDATE users SET lang=?, lang_chosen=1 WHERE user_id=?").bind(normalizeLang(lang) || "en", Number(userId)).run();
    return true;
  } catch (err) {
    console.error("setUserLang failed (migration 0012 applied?)", err?.message || err);
    return false;
  }
}

